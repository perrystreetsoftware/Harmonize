import Foundation
import XCTest
@testable import HarmonizeSkillsCore

final class SkillsEmitterTests: XCTestCase {
    private var repository: FixtureRepository!
    private var config: ProjectConfig!

    override func setUpWithError() throws {
        repository = try FixtureRepository()
        config = ProjectConfig(
            repoRoot: repository.root,
            skillsOutput: repository.root.appendingPathComponent(".agents/skills"),
            skillName: "harmonize"
        )
    }

    override func tearDown() {
        repository.remove()
    }

    private func catalog(
        rules: [StaticRule],
        descriptions: [String: String] = ["viewmodel": "Rules for ViewModels."]
    ) -> StaticCatalog {
        var categories: [String: StaticCategory] = [:]
        for (name, description) in descriptions {
            categories[name] = StaticCategory(caseName: name, name: name, description: description)
        }
        return StaticCatalog(rules: rules, categories: categories)
    }

    private func render(_ catalog: StaticCatalog) throws -> [String: String] {
        let result = try SkillsEmitter.render(catalog, config: config, generatorHint: "swift package harmonize-skills")
        return Dictionary(uniqueKeysWithValues: result.files.map { ($0.relativePath, $0.content) })
    }

    func testSkillFileListsLayersAndUpfrontRulesInTheDescription() throws {
        let files = try render(catalog(rules: [
            makeRule(id: "a-rule"),
            makeRule(id: "final-classes", title: "Classes must be final.", category: "", disclosure: "upfront"),
        ]))
        let skill = try XCTUnwrap(files["SKILL.md"])

        XCTAssertTrue(skill.hasPrefix("---\nname: harmonize\ndescription: \""))
        XCTAssertTrue(skill.contains("for these layers: viewmodel."))
        XCTAssertTrue(skill.contains("Always: Classes must be final."))
        XCTAssertTrue(skill.contains("- [viewmodel](references/viewmodel.md) (1 rule): Rules for ViewModels."))
        XCTAssertTrue(skill.contains("Full rule: [final-classes](references/all/final-classes.md)"))
        XCTAssertNotNil(files["references/all/final-classes.md"])
    }

    func testLayerFileLinksEachRuleAndRuleFileHasAllSections() throws {
        let files = try render(catalog(rules: [makeRule(id: "a-rule", title: "Do not [do] this.")]))

        let layer = try XCTUnwrap(files["references/viewmodel.md"])
        XCTAssertTrue(layer.contains("Rules for ViewModels."))
        XCTAssertTrue(layer.contains("- [Do not \\[do\\] this.](viewmodel/a-rule.md)"), layer)

        let rule = try XCTUnwrap(files["references/viewmodel/a-rule.md"])
        XCTAssertTrue(rule.hasPrefix("# Do not [do] this.\n"))
        for section in ["## Why\n\nWhy.", "## How to fix\n\nFix.", "## Bad\n\n```swift\nbad\n```", "## Good\n\n```swift\ngood\n```"] {
            XCTAssertTrue(rule.contains(section), section)
        }
        XCTAssertTrue(rule.contains("Source: [SomeRule.swift]("), rule)
    }

    func testMultiLineTitlesBecomeOneLine() throws {
        let files = try render(catalog(rules: [
            makeRule(id: "split", title: "Line one,\n    line two."),
            makeRule(id: "always", title: "Always one,\n    always two.", category: "", disclosure: "upfront"),
        ]))

        XCTAssertTrue(try XCTUnwrap(files["SKILL.md"]).contains("Always: Always one, always two."))
        XCTAssertTrue(try XCTUnwrap(files["SKILL.md"]).contains("### Always one, always two."))
        XCTAssertTrue(try XCTUnwrap(files["references/viewmodel.md"]).contains("- [Line one, line two.](viewmodel/split.md)"))
        XCTAssertTrue(try XCTUnwrap(files["references/viewmodel/split.md"]).hasPrefix("# Line one, line two.\n"))
    }

    func testOnlyTheSkillFileCarriesTheGeneratedMarker() throws {
        let files = try render(catalog(rules: [makeRule(id: "a-rule")]))
        let marker = "<!-- Generated by harmonize-skills"

        XCTAssertTrue(try XCTUnwrap(files["SKILL.md"]).contains(marker))
        XCTAssertTrue(try XCTUnwrap(files["SKILL.md"]).contains("`swift package harmonize-skills`"))
        XCTAssertFalse(try XCTUnwrap(files["references/viewmodel.md"]).contains(marker))
        XCTAssertFalse(try XCTUnwrap(files["references/viewmodel/a-rule.md"]).contains(marker))
    }

    func testDeferredRulesAreNotRendered() throws {
        let files = try render(catalog(rules: [
            makeRule(id: "shown"),
            makeRule(id: "hidden", disclosure: "deferred"),
        ]))

        XCTAssertNil(files["references/viewmodel/hidden.md"])
        XCTAssertFalse(try XCTUnwrap(files["references/viewmodel.md"]).contains("hidden"))
    }

    func testMissingCategoryDescriptionProducesAWarningAndAFallback() throws {
        let result = try SkillsEmitter.render(catalog(rules: [makeRule(id: "r")], descriptions: [:]), config: config, generatorHint: "x")

        XCTAssertEqual(result.warnings, ["category 'viewmodel' has no categoryDescription; using a generic one"])
        let layer = try XCTUnwrap(result.files.first { $0.relativePath == "references/viewmodel.md" })
        XCTAssertTrue(layer.content.contains("Harmonize architecture rules for the viewmodel layer."))
    }

    func testTooLongDescriptionFails() {
        let longTitle = String(repeating: "x", count: 600)
        let rules = [
            makeRule(id: "one", title: longTitle, category: "", disclosure: "upfront"),
            makeRule(id: "two", title: longTitle, category: "", disclosure: "upfront"),
        ]

        XCTAssertThrowsError(try SkillsEmitter.render(catalog(rules: rules), config: config, generatorHint: "x")) { error in
            XCTAssertTrue("\(error)".contains("the limit is 1024"), "\(error)")
        }
    }

    func testInvalidSkillNamesFail() {
        for name in ["", "Harmonize", "harmonize-", "-harmonize", "har--monize", "har monize", String(repeating: "a", count: 65)] {
            XCTAssertThrowsError(try SkillsEmitter.validatedSkillName(name), name)
        }
        XCTAssertEqual(try SkillsEmitter.validatedSkillName("harmonize-2"), "harmonize-2")
    }

    func testWriteRefusesPathsOutsideTheSkillDirectory() throws {
        for path in ["references/../../../other-skill/SKILL.md", "/etc/skill.md", ""] {
            XCTAssertThrowsError(
                try SkillsEmitter.write([GeneratedFile(relativePath: path, content: "x")], config: config),
                path
            ) { error in
                XCTAssertTrue("\(error)".contains("outside the skill directory"), "\(error)")
            }
        }
    }

    func testWriteIsIdempotentAndSweepsStaleReferences() throws {
        let catalog = self.catalog(rules: [makeRule(id: "a-rule")])
        let result = try SkillsEmitter.render(catalog, config: config, generatorHint: "x")

        let first = try SkillsEmitter.write(result.files, config: config)
        XCTAssertEqual(first.written.sorted(), ["SKILL.md", "references/viewmodel.md", "references/viewmodel/a-rule.md"])
        XCTAssertTrue(first.unchanged.isEmpty)

        let stale = config.skillsOutput.appendingPathComponent("harmonize/references/logic/old-rule.md")
        try FileManager.default.createDirectory(at: stale.deletingLastPathComponent(), withIntermediateDirectories: true)
        try "stale".write(to: stale, atomically: true, encoding: .utf8)

        let second = try SkillsEmitter.write(result.files, config: config)
        XCTAssertTrue(second.written.isEmpty)
        XCTAssertEqual(second.unchanged.count, 3)
        XCTAssertEqual(second.removed, ["references/logic/old-rule.md"])
        XCTAssertFalse(FileManager.default.fileExists(atPath: stale.path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: stale.deletingLastPathComponent().path), "empty folder is removed")
    }
}
